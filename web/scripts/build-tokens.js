// Builds src/lib/tokens/generated/{tokens.css,tokens.ts} from tokens/tokens.json
// (W3C Design Tokens format). Run by `yarn dev`, `yarn build` and `yarn check`.
//
// - CSS: custom properties for everything except primitives, named by token path
//   (`space.sm` -> `--space-sm`). `semantic.light.*` goes on :root and
//   `semantic.dark.*` into a prefers-color-scheme media query, both without the
//   `semantic.<mode>` prefix (`--color-paper`).
// - TS: the same values for canvas drawing, which cannot read CSS custom
//   properties cheaply every frame. Dimensions become numbers in px.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const source = JSON.parse(readFileSync(join(root, 'tokens/tokens.json'), 'utf8'))
const outDir = join(root, 'src/lib/tokens/generated')

/** Extension key for a unit appended to unitless values in CSS (e.g. `%` for font-stretch). */
const CSS_UNIT = 'dev.silly-demos.css-unit'

/** Flattens the token tree, inheriting `$type` and the CSS unit from enclosing groups. */
function collect(node, path = [], type = undefined, unit = undefined, out = []) {
  const nodeType = node.$type ?? type
  const nodeUnit = node.$extensions?.[CSS_UNIT] ?? unit
  if ('$value' in node) {
    out.push({ path, type: nodeType, unit: nodeUnit, value: node.$value })
    return out
  }
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$') || typeof child !== 'object' || child === null) continue
    collect(child, [...path, key], nodeType, nodeUnit, out)
  }
  return out
}

const tokens = collect(source)
const byPath = new Map(tokens.map(t => [t.path.join('.'), t]))

/** Follows `{group.token}` references to a concrete value. */
function resolve(value, seen = new Set()) {
  if (typeof value !== 'string') return value
  const match = /^\{([^}]+)\}$/.exec(value)
  if (!match) return value
  const ref = match[1]
  if (seen.has(ref)) throw new Error(`Circular token reference: ${[...seen, ref].join(' -> ')}`)
  const target = byPath.get(ref)
  if (!target) throw new Error(`Unknown token reference {${ref}}`)
  return resolve(target.value, new Set([...seen, ref]))
}

function cssValue(type, value, unit = '') {
  switch (type) {
    case 'dimension':
      return `${value.value}${value.unit}`
    case 'fontFamily':
      return value.map(f => (/\s/.test(f) ? `'${f}'` : f)).join(', ')
    default:
      return `${value}${unit}`
  }
}

function tsValue(type, value) {
  switch (type) {
    case 'dimension':
      if (value.unit !== 'px') throw new Error(`Only px dimensions are supported, got ${value.unit}`)
      return value.value
    case 'fontFamily':
      return cssValue(type, value)
    default:
      return value
  }
}

const camel = s => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())

/** Splits tokens into mode-independent ones and per-mode semantic ones. */
function partition() {
  const base = []
  const modes = {}
  for (const t of tokens) {
    const [head, ...rest] = t.path
    if (head === 'primitive') continue
    if (head === 'semantic') {
      const [mode, ...name] = rest
      ;(modes[mode] ??= []).push({ ...t, path: name })
    } else {
      base.push(t)
    }
  }
  return { base, modes }
}

const { base, modes } = partition()
const declarations = list =>
  list.map(t => `  --${t.path.join('-')}: ${cssValue(t.type, resolve(t.value), t.unit)};`).join('\n')

const css = `/* Generated by scripts/build-tokens.js from tokens/tokens.json. Do not edit. */

:root {
${declarations(base)}
${declarations(modes.light)}
  color-scheme: light dark;
}

@media (prefers-color-scheme: dark) {
  :root {
${declarations(modes.dark).replace(/^/gm, '  ')}
  }
}
`

/** Nested object keyed by token path (camel-cased), for the TS module. */
function tree(list) {
  const out = {}
  for (const t of list) {
    let node = out
    const keys = t.path.map(camel)
    for (const key of keys.slice(0, -1)) node = node[key] ??= {}
    node[keys.at(-1)] = tsValue(t.type, resolve(t.value))
  }
  return out
}

const palette = Object.fromEntries(Object.entries(modes).map(([mode, list]) => [mode, tree(list).color]))
const ts = `// Generated by scripts/build-tokens.js from tokens/tokens.json. Do not edit.

/** Semantic colors per color scheme. */
export const palette = ${JSON.stringify(palette, null, 2)} as const

export type ColorScheme = keyof typeof palette
/** One scheme's colors; values widened to string so schemes are interchangeable. */
export type Palette = { readonly [K in keyof (typeof palette)['light']]: string }

/** Mode-independent tokens; dimensions in px. */
export const tokens = ${JSON.stringify(tree(base), null, 2)} as const
`

mkdirSync(outDir, { recursive: true })
writeFileSync(join(outDir, 'tokens.css'), css)
writeFileSync(join(outDir, 'tokens.ts'), ts)
console.log(`tokens: ${tokens.length} tokens -> ${outDir}`)
